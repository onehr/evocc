"""The N07 integer lane needs a vendor body, not a local ISA substitute."""
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


class VendorSliceTest(unittest.TestCase):
    def test_executable_vendor_slice_and_original_decode_are_present(self):
        source = (ROOT / "targets/aarch64/isa/integer.sail").read_text()
        self.assertIn("Generated by tools/isa_model_slice.py", source)
        self.assertIn("function AddWithCarry (x, y, carry_in)", source)
        self.assertIn("function clause __DecodeA64_DataProcReg", source)
        self.assertIn("end __DecodeA64", source)
        self.assertIn("NO EXPRESS OR IMPLIED LICENSES", source)


if __name__ == "__main__":
    unittest.main()
