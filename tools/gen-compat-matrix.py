#!/usr/bin/env python3
"""Generate the book's retained compatibility matrix from ladder receipts."""
import argparse
from datetime import datetime
import html
import json
from pathlib import Path
import re
import sys

import bench


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "book/src/compatibility.md"
LINK = "https://github.com/onehr/evocc/blob/main/tests/contracts/"


def cell(value):
    if value is None or value == "":
        value = "unknown"
    return html.escape(str(value), quote=False).replace("|", "&#124;").replace("\n", " ")


def counts(values):
    return ", ".join(f"{key}={value}" for key, value in sorted(values.items())) or "none"


def input_identity(name, data):
    source = data.get("suites", {}).get(name, data.get("csmith", {}) if name == "csmith" else data)
    pin = source.get("pin", {})
    if isinstance(pin, str):
        commit = re.search(r"\b[0-9a-f]{40}\b", pin)
        return pin, source.get("sourceCommit", commit.group() if commit else "unknown")
    version = next((pin[key] for key in ("used", "version", "ref", "roadmapRelease") if pin.get(key)),
                   source.get("version", "unknown"))
    commit = source.get("sourceCommit", pin.get("commit", source.get("commit", "unknown")))
    return version, commit


def run_date(run):
    try:
        return datetime.strptime(run, "%Y%m%dT%H%M%SZ").strftime("%Y-%m-%d %H:%M:%S UTC")
    except (TypeError, ValueError):
        return "unknown"


def render():
    paths = sorted((ROOT / "tests/contracts").glob("ladder-*-receipt.json"))
    if not paths:
        raise ValueError("no ladder receipts found")
    table, details = [], []
    for path in paths:
        receipt = json.loads(path.read_text(encoding="utf-8"))
        data = receipt.get("latest", receipt)
        stem = path.name.removeprefix("ladder-").removesuffix("-receipt.json")
        names = sorted(data["suites"]) if stem == "e0" else [stem]
        if not names:
            raise ValueError(f"{path.name}: no recorded suites")
        for name in names:
            row = bench.metrics(name, data)
            version, commit = input_identity(name, data)
            run = data.get("run")
            checkout = data.get("subject") if stem in ("e0", "csmith") else None
            pin = version if version != "unknown" else f"commit {commit}" if commit != "unknown" else "unknown"
            label = f"[{cell(name)}]({LINK}{path.name})"
            values = [label, cell(pin), cell(checkout or "not recorded"), row["status"],
                      f'{row["passed"]}/{row["total"]} {row["kind"]}', cell(run_date(run))]
            table.append("| " + " | ".join(values) + " |\n")
            details.extend([
                f"\n### {cell(name)}\n\n",
                f"Input commit: {cell(commit)}. Target: {cell(data.get('target'))}.\n",
                f"Recorded checkout: {cell(checkout or 'not recorded')}; run: {cell(run)}.\n",
                f"Compiler SHA-256: {cell(data.get('compilerSha256', data.get('driverSha256')))}.\n",
                f"Scope: {cell(row['note'])}."
                f"{' ' + cell(data['scope']) + '.' if data.get('scope') else ''}\n",
            ])
            if "compiled" in row:
                details.append(f"Compiled: {row['compiled']}.\n")
            if row["baselineFailures"]:
                details.append(f"Baseline failures: {row['baselineFailures']}.\n")
            for title, key in (("Raw outcomes", "outcomes"), ("Reviewed dispositions", "dispositions"),
                               ("Refusals", "refusals")):
                if row.get(key):
                    details.append(f"{title}: {cell(counts(row[key]))}.\n")
            for kind, outcomes in sorted(row.get("testOutcomes", {}).items()):
                details.append(f"{cell(kind)} test outcomes: {cell(counts(outcomes))}.\n")
    return "".join([
        "# Retained compatibility\n\n",
        "<!-- Generated by tools/gen-compat-matrix.py. Edit the source receipts, not this file. -->\n\n",
        "These are retained measurements; artifacts are not revalidated by this generator.\n",
        "They do not establish compatibility of the current checkout, every build configuration,\n",
        "or a release archive. Each linked receipt keeps its own input, compiler, build\n",
        "adjustments and test selection.\n\n",
        "The result uses the existing benchmark normalization. PASS covers only the recorded\n",
        "selection. PROFILE_CLEAN is not an all-program PASS; skips, unavailable oracles,\n",
        "baseline failures and partial compilation remain visible. Passing/total counts\n",
        "programs or installed units as labeled, not a common cross-project denominator.\n",
        "Doom is a separate headless replay, not an addition to the frozen application denominator.\n\n",
        "Input version/ref/commit describes the measured project, not EvoCC. Missing provenance is\n",
        "unknown or not recorded, never filled from today's version or Git HEAD. A recorded checkout is\n",
        "the recorder's revision, not an inferred compiler-binary source revision. Dates come\n",
        "from recorded UTC run identifiers; they are not source-release or regeneration dates.\n\n",
        "| Receipt / lane | Input version / ref / commit | EvoCC checkout | Retained result | Passing / total | Run date |\n",
        "|---|---|---|---|---|---|\n", *table, "\n## Provenance and scope\n", *details,
        "\nRegenerate with `python3 tools/gen-compat-matrix.py`; "
        "`python3 tools/gen-compat-matrix.py --check` rejects a stale chapter without writing it.\n",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="reject a stale chapter without writing")
    args = parser.parse_args()
    try:
        expected = render()
        if args.check:
            if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
                raise ValueError("compatibility matrix is stale; run python3 tools/gen-compat-matrix.py")
        else:
            OUTPUT.write_text(expected, encoding="utf-8")
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"compatibility matrix: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
