#!/usr/bin/env python3
"""Select verbatim named spans from the pinned Arm ASL-to-Sail model.

This is a bounded source selector, not an instruction-semantics translator.
The original full source is an external input; only the selected dependency
closure and its license are checked in. No network operation is performed.
"""
import argparse
import hashlib
import json
from pathlib import Path

COMMIT = "1bf2e5574ba9d704639a28401b6a387dcb113cae"
HASHES = {
    "prelude.sail": "81260319293bbc6b1512cf6d10f181ad401ce20b147d46a5e8c80a3c89e2db41",
    "builtins.sail": "ab4473cdfcb885e3abe8013cfe9f557e62e6c22d903af16263c5b6af06c6bf8f",
    "v8_base.sail": "7c7a9c92e05cedb7202183160db96dd2b9c1de6cde73a70816159c6ddf2d1b49",
    "instrs64.sail": "f46630385fb146b2f74254566a16528ae2c26d41246fca84beeb49a8d35c7fc8",
    "decode_start.sail": "01ce1d2df4951dcdc4d4ab5fb6eb8c1f9436d3476707d290d42f235e609b644e",
    "decode_end.sail": "be7d7b3a71e7b1b50cb53a031b670c70910b9ab1a2a1506a83e12eebde6760a6",
    "LICENSE-arm-v9.4-a": "121df4677b246ccb78e33f257c131ee6164067a52c01235bd3d272c82e44dcc4",
}
FAMILIES = (
    "arithmetic_add_sub_shiftedreg", "arithmetic_add_sub_immediate",
    "logical_immediate", "logical_shiftedreg", "shift_variable", "bitfield",
    "arithmetic_mul_uniform_add_sub", "ins_ext_insert_movewide",
)


def digest(contents):
    return hashlib.sha256(contents).hexdigest()


def span(source, start, end):
    if source.count(start) != 1:
        raise ValueError("non-unique source anchor: " + start.decode())
    low = source.index(start)
    high = source.index(end, low + len(start))
    return low, high


def outputs(folder):
    original = {name: (folder / name).read_bytes() for name in HASHES}
    for name, contents in original.items():
        if digest(contents) != HASHES[name]:
            raise ValueError("pinned upstream source differs: " + name)
    pieces, records = [], []

    def select(name, low, high):
        contents = original[name][low:high]
        pieces.append(contents)
        records.append(dict(source=name, byte_start=low, byte_end=high,
                            sha256=digest(contents)))

    base = original["v8_base.sail"]
    select("v8_base.sail", 0, base.index(b"bitfield Configuration_Type"))
    for start, end in (
        (b"struct ProcState =", b"register ShouldAdvanceIT"),
        (b"register R0 :", b"val register_ref :"),
        (b"enum MoveWideOp =", b"\nenum "),
        (b"enum ShiftType =", b"\nenum "),
        (b"enum LogicalOp =", b"\nenum "),
        (b"val X_set :", b"\nval "),
        (b"val X_read :", b"\nval "),
        (b"val AddWithCarry :", b"\nval "),
        (b"val DecodeShift :", b"\nval "),
        (b"val ShiftReg :", b"\nval "),
        (b"val DecodeBitMasks :", b"\nval "),
    ):
        select("v8_base.sail", *span(base, start, end))
    select("decode_start.sail", 0, len(original["decode_start.sail"]))
    instructions = original["instrs64.sail"]
    for family in FAMILIES:
        start = ("val execute_aarch64_instrs_integer_" + family + " :").encode()
        select("instrs64.sail", *span(instructions, start, b"\nval execute_"))
    select("decode_end.sail", 0, len(original["decode_end.sail"]))
    header = ("// Generated by tools/isa_model_slice.py; verbatim upstream spans.\n"
              "// Arm ASL-to-Sail commit " + COMMIT + ".\n"
              '$include "prelude.sail"\n$include "builtins.sail"\n'
              '$include "boundary.sail"\n').encode()
    result = {"integer.sail": header + b"\n\n".join(pieces) + b"\n",
              "prelude.sail": original["prelude.sail"],
              "builtins.sail": original["builtins.sail"],
              "LICENSE": original["LICENSE-arm-v9.4-a"]}
    provenance = dict(repository="https://github.com/rems-project/sail-arm", commit=COMMIT,
                      path="arm-v9.4-a/src", inputs=HASHES,
                      selector_sha256=digest(Path(__file__).read_bytes()),
                      spans=records, outputs={name: digest(value) for name, value in result.items()},
                      boundary="boundary.sail and runtime.sail are project reset/I/O/domain glue, not vendor semantics")
    result["provenance.json"] = (json.dumps(provenance, indent=2) + "\n").encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", required=True, type=Path)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "targets/aarch64/isa")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, contents in outputs(args.upstream).items():
        path = args.output / name
        if args.check:
            if not path.is_file() or path.read_bytes() != contents:
                raise ValueError("generated vendor slice differs: " + str(path))
        elif not path.is_file() or path.read_bytes() != contents:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(contents)


if __name__ == "__main__":
    main()
